/**
 * Writes the Android app's translatable strings from messages/<locale>.json, so translators see
 * them in the same files (and the same `i18n:missing` stubs) as the web UI. Each `android_<name>`
 * key becomes `<string name="<name>">` in res/values[-<locale>]/generated_strings.xml; a key a
 * locale lacks is left out, and Android falls back to values/ (en) for it, as Paraglide does.
 * The output is gitignored: `i18n:compile` (so `npm install` and `npm run check`) and every Vite
 * build regenerate it.
 *
 * Usage:
 *   node scripts/android-strings.js
 */

import { existsSync, mkdirSync, readdirSync, unlinkSync, writeFileSync } from 'fs';
import { join } from 'path';
import { fileURLToPath } from 'url';
import { BASE_LOCALE, MESSAGES_DIR, listConfiguredLocales, readJson } from './i18n-shared.js';

const RES_DIR = join(MESSAGES_DIR, '..', 'android', 'app', 'src', 'main', 'res');
const FILE_NAME = 'generated_strings.xml';
const KEY_PREFIX = 'android_';

/**
 * The strings Java reads, each with its inputs in getString()'s argument order: Android
 * placeholders are positional (%1$s), so a translation may move {device} before {host} and still
 * get the right value.
 *
 * @type {Record<string, string[]>}
 */
export const ANDROID_STRINGS = {
	link_channel: [],
	link_notification: ['host'],
	link_notification_device: ['host', 'device'],
	link_unlink: []
};

/**
 * res/ folder for a locale: `values` for en, `values-ko`, and BCP 47 form for `pt-BR` etc.
 * @param {string} locale
 */
export const valuesDir = (locale) => {
	if (locale === BASE_LOCALE) return 'values';
	const tags = locale.split('-');
	return tags.length === 1 ? `values-${locale}` : `values-b+${tags.join('+')}`;
};

/**
 * A Paraglide message as an Android string resource value, escaped for aapt.
 * @param {string} name
 * @param {unknown} message
 */
export const toAndroidValue = (name, message) => {
	if (typeof message !== 'string') {
		throw new Error(`${KEY_PREFIX}${name}: Android strings can't be plurals or variants.`);
	}
	const inputs = ANDROID_STRINGS[name];
	// getString() without arguments doesn't format, so only formatted strings double their %.
	let value = inputs.length > 0 ? message.replaceAll('%', '%%') : message;
	value = value.replace(/\{(\w+)\}/g, (_, input) => {
		const i = inputs.indexOf(input);
		if (i < 0) throw new Error(`${KEY_PREFIX}${name}: unknown input {${input}}.`);
		return `%${i + 1}$s`;
	});
	value = value
		.replaceAll('\\', '\\\\')
		.replaceAll('&', '&amp;')
		.replaceAll('<', '&lt;')
		.replaceAll('>', '&gt;')
		.replaceAll("'", "\\'")
		.replaceAll('"', '\\"')
		.replaceAll('\n', '\\n');
	// A leading @ or ? would be read as a resource reference.
	return /^[@?]/.test(value) ? `\\${value}` : value;
};

/** @param {string} locale @param {Record<string, unknown>} messages */
const xml = (locale, messages) => {
	const lines = Object.keys(ANDROID_STRINGS)
		.filter((name) => `${KEY_PREFIX}${name}` in messages)
		.map(
			(name) =>
				`    <string name="${name}">${toAndroidValue(name, messages[`${KEY_PREFIX}${name}`])}</string>`
		);
	if (lines.length === 0) return null;
	return [
		`<?xml version='1.0' encoding='utf-8'?>`,
		`<!-- Generated by scripts/android-strings.js from messages/${locale}.json; edit that instead. -->`,
		`<resources>`,
		...lines,
		`</resources>`,
		``
	].join('\n');
};

export function writeAndroidStrings() {
	const written = new Set();
	for (const locale of listConfiguredLocales()) {
		const content = xml(locale, readJson(`${locale}.json`));
		if (!content) continue;
		const dir = join(RES_DIR, valuesDir(locale));
		mkdirSync(dir, { recursive: true });
		writeFileSync(join(dir, FILE_NAME), content);
		written.add(dir);
	}
	// A locale that was dropped, or lost all its Android keys, must not keep shipping old strings.
	for (const entry of readdirSync(RES_DIR)) {
		const dir = join(RES_DIR, entry);
		if (entry.startsWith('values') && !written.has(dir) && existsSync(join(dir, FILE_NAME))) {
			unlinkSync(join(dir, FILE_NAME));
		}
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeAndroidStrings();
